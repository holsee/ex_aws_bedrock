defmodule ExAws.Bedrock.EventStream do
  @moduledoc """
  Handle streaming of output generated by models.

  The model detail returned by `ExAws.Bedrock.get_foundation_model/1` must have:

      responseStreamingSupported = true

  This requires `hackney` otherwise we will fail at runtime. It also assumes `Jason` is available
  but we can improve this to lookup the ExAws JSON coded.

  [AWS API Docs](https://docs.aws.amazon.com/bedrock/latest/APIReference/API_runtime_ResponseStream.html)
  """

  defdelegate build_request_url(post_operation, config), to: ExAws.Request.Url, as: :build

  @content_type "application/vnd.amazon.eventstream"

  if {:module, :hackney} == Code.ensure_loaded(:hackney) &&
       Kernel.function_exported?(:hackney, :post, 4) do
    # hackney >= 4 moved default_ua/0 from :hackney_request to :hackney
    if function_exported?(:hackney, :default_ua, 0) do
      @http_ua :hackney.default_ua()
    else
      @http_ua :hackney_request.default_ua()
    end

    @library_version Application.spec(:ex_aws_bedrock)[:vsn]
    @user_agent "#{@http_ua} ex_aws/bedrock/#{@library_version}"
    @headers [
      {"accept", @content_type},
      {"content-type", "application/json"},
      {"user-agent", @user_agent},
      {"x-amzn-bedrock-accept", "*/*"}
    ]
    # `protocols: [:http1]` is required under hackney 4.x: over an ALPN-negotiated
    # HTTP/2 connection its async streaming does not deliver `{:hackney_response, _}`
    # messages to the caller, so the status/data receives below would block
    # forever. HTTP/1.1 chunked transfer is what the Bedrock event-stream API
    # serves anyway. (The option is ignored by hackney 1.x, which has no HTTP/2.)
    @hackney_options [{:async, :once}, {:protocols, [:http1]}]

    @doc """
    Stream of chunks from the response stream.

    Raises on any error.

    [AWS API Docs](https://docs.aws.amazon.com/bedrock/latest/APIReference/API_runtime_ResponseStream.html)
    """
    def stream_objects!(%{service: service, data: data} = post_operation, _opts, config) do
      encoded_data = Jason.encode!(data)
      url = build_request_url(post_operation, config)
      config = Map.put(config, :service_override, :bedrock)

      {:ok, full_headers} =
        ExAws.Auth.headers(
          :post,
          url,
          service,
          config,
          @headers,
          encoded_data
        )

      hackney_opts = hackney_options(config)

      request_fun = fn [] ->
        {:ok, ref} = :hackney.post(url, full_headers, encoded_data, hackney_opts)

        receive do
          {:hackney_response, ^ref, {:status, 200, _reason}} ->
            ref

          {:hackney_response, ^ref, {:status, status, reason}} ->
            {:error, status, reason}

          {:hackney_response, ^ref, {:error, {:closed, :timeout}}} ->
            :closed
        end
      end

      stream =
        Stream.resource(
          fn -> request_fun.([]) end,
          fn
            :closed ->
              {:halt, []}

            {:error, status, reason} ->
              raise ExAws.Error, "#{to_string(status)}: #{to_string(reason)}"

            # hackney 4.x async post returns a connection PID; hackney 1.x returned
            # a Reference. Accept both so streaming works across hackney versions.
            ref when is_reference(ref) or is_pid(ref) ->
              :ok = :hackney.stream_next(ref)

              receive do
                {:hackney_response, ^ref, {:headers, headers}} ->
                  verify_event_stream!(headers)
                  verify_chunked!(headers)
                  {[], ref}

                {:hackney_response, ^ref, :done} ->
                  {:halt, []}

                {:hackney_response, ^ref, data} ->
                  {[data], ref}
              end
          end,
          &Function.identity/1
        )

      # Decode with a rolling binary buffer so a single event-stream frame that
      # is split across two hackney chunks is reassembled rather than dropped.
      # (Per-chunk `flat_map` decoding loses any frame straddling a chunk
      # boundary — which happens routinely for larger/slower model responses.)
      Stream.transform(stream, <<>>, &decode_buffered/2)
    end

    @doc """
    Builds the hackney options for the streaming request.

    Merges caller-provided options from the ExAws config `:http_opts` (e.g.
    `recv_timeout`, `connect_timeout`, `pool`) on top of the async-streaming
    defaults. Without this, the stream would always use hackney's built-in
    `recv_timeout` (5s) and drop slow responses regardless of the timeout the
    caller configured.

    The streaming defaults win on conflicting keys, so the async-streaming mode
    (`async: :once`) can't be accidentally disabled by caller options.
    """
    def hackney_options(config) do
      config
      |> Map.get(:http_opts, [])
      |> Keyword.merge(@hackney_options)
    end

    defp verify_event_stream!(headers) do
      verify_header!(headers, "Content-Type", @content_type)
    end

    defp verify_chunked!(headers) do
      verify_header!(headers, "Transfer-Encoding", "chunked")
    end

    defp verify_header!(headers, header, expected) do
      case List.keyfind!(headers, header, 0) do
        {_, ^expected} ->
          true

        {_, content_type} ->
          raise ExAws.Error, "Accepts #{expected}, received #{to_string(content_type)}"
      end
    end
  else
    def stream_objects!(_, _, _) do
      raise "Bedrock response streaming requires hackney in your mix dependencies"
    end
  end

  @doc false
  @spec decode_chunk(binary()) :: list({:chunk, map()} | {:bad_chunk, binary(), term()})
  def decode_chunk(data) do
    decode_chunks(data, [])
  end

  defp decode_chunks(<<>>, acc), do: Enum.reverse(acc)

  defp decode_chunks(data, acc) do
    case parse_chunk(data) do
      {:ok, chunk, rest} ->
        decode_chunks(rest, [{:chunk, chunk} | acc])

      {:error, reason, rest} ->
        decode_chunks(rest, [{:bad_chunk, data, reason} | acc])

      :incomplete ->
        [{:incomplete_chunk, data} | acc]
    end
  end

  # `Stream.transform/3` reducer: prepend the buffered remainder from the
  # previous hackney chunk, emit every complete frame, and carry the trailing
  # incomplete bytes forward as the new accumulator.
  @doc false
  @spec decode_buffered(binary(), binary()) ::
          {[{:chunk, map()} | {:bad_chunk, binary(), term()}], binary()}
  def decode_buffered(data, buffer) do
    extract_frames(buffer <> data, [])
  end

  defp extract_frames(data, acc) do
    case parse_chunk(data) do
      {:ok, chunk, rest} ->
        extract_frames(rest, [{:chunk, chunk} | acc])

      {:error, reason, rest} ->
        extract_frames(rest, [{:bad_chunk, data, reason} | acc])

      :incomplete ->
        {Enum.reverse(acc), data}
    end
  end

  @uint32_size 4
  @checksum_size 4
  # prelude_length = message_total_length + headers_length + prelude_checksum
  @prelude_length @uint32_size * 3
  # message_overhead = prelude + message_checksum
  @message_overhead @prelude_length + @checksum_size
  defp parse_chunk(
         <<
           message_total_length::unsigned-32,
           headers_length::unsigned-32,
           prelude_checksum::unsigned-32,
           headers::binary-size(headers_length),
           rest::binary
         >> = data
       )
       when byte_size(data) >= message_total_length do
    message_length = message_total_length - @message_overhead
    body_length = message_length - headers_length

    if byte_size(rest) >= body_length + @checksum_size do
      <<
        body::binary-size(body_length),
        message_checksum::unsigned-32,
        next_data::binary
      >> = rest

      prelude = <<message_total_length::unsigned-32, headers_length::unsigned-32>>

      with :ok <- verify_prelude_checksum(prelude, prelude_checksum),
           :ok <-
             verify_message_checksum(prelude, prelude_checksum, headers, body, message_checksum),
           {:ok, chunk} <- process_chunk(body) do
        {:ok, chunk, next_data}
      else
        {:error, reason} -> {:error, reason, next_data}
      end
    else
      :incomplete
    end
  end

  defp parse_chunk(data) when byte_size(data) < @prelude_length do
    :incomplete
  end

  # Prelude is readable but the full message has not arrived yet — signal the
  # caller to buffer and retry once more bytes are appended, rather than
  # discarding a partial frame as invalid.
  defp parse_chunk(<<message_total_length::unsigned-32, _rest::binary>> = data)
       when byte_size(data) < message_total_length do
    :incomplete
  end

  defp parse_chunk(_data) do
    {:error, :invalid_chunk, <<>>}
  end

  defp verify_prelude_checksum(prelude, checksum) do
    if crc32(prelude) == checksum do
      :ok
    else
      {:error, :invalid_prelude_checksum}
    end
  end

  defp verify_message_checksum(prelude, prelude_checksum, headers, body, checksum) do
    message = prelude <> <<prelude_checksum::unsigned-32>> <> headers <> body

    if crc32(message) == checksum do
      :ok
    else
      {:error, :invalid_message_checksum}
    end
  end

  defp crc32(data) do
    :erlang.crc32(data)
  end

  defp process_chunk(body) do
    with {:ok, %{"bytes" => bytes}} <- Jason.decode(body),
         {:ok, json} <- Base.decode64(bytes),
         {:ok, payload} <- Jason.decode(json) do
      {:ok, payload}
    else
      {:error, error} ->
        {:error, error}

      error ->
        {:error, error}
    end
  end
end
